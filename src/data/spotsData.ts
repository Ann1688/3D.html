export function getSpotById(id: string): Spot | undefined {
  return ALL_SPOTS.find((s) => s.id === id);
}

export function getSpotsByRegion(region: string): Spot[] {
  if (region === 'all') return ALL_SPOTS;
  return ALL_SPOTS.filter((s) => s.region === region);
}

export function getSpotsByCategory(category: string): Spot[] {
  return ALL_SPOTS.filter((s) => s.category === category);
}
